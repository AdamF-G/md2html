// genwidths writes systemsans_widths.go: Inter's advance widths for
// U+0020–U+024F, the proxy md2html measures system-sans chart text with.
//
//	go run ./internal/charts/internal/genwidths -font Inter.ttf -src <google/fonts commit> > internal/charts/systemsans_widths.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"

	"github.com/tdewolff/font"
)

func main() {
	path := flag.String("font", "", "Inter TrueType file")
	from := flag.String("src", "", "where the file came from, recorded in the output")
	flag.Parse()
	b, err := os.ReadFile(*path)
	if err != nil {
		log.Fatal(err)
	}
	f, err := font.ParseSFNT(b, 0)
	if err != nil {
		log.Fatal(err)
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by genwidths from Inter (SIL OFL 1.1), %s. DO NOT EDIT.\n\npackage charts\n\n", *from)
	fmt.Fprintf(&out, "const systemSansUPM = %d\n\n// systemSansAdvance[r-0x20] is the advance of rune r.\nvar systemSansAdvance = [...]uint16{", f.UnitsPerEm())
	for r := rune(0x20); r <= 0x24f; r++ {
		if (r-0x20)%16 == 0 {
			fmt.Fprint(&out, "\n\t")
		}
		fmt.Fprintf(&out, "%d, ", f.GlyphAdvance(f.GlyphIndex(r)))
	}
	fmt.Fprintln(&out, "\n}")
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	os.Stdout.Write(src)
}
